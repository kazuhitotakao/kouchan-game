<!-- ここのCSSには scoped を付けない（＝ページ全体に効く共通のCSS）

     ページの入れかわり（/ ⇄ /soundtrack）に使うクラスは、
     Nuxtがページの外側から付けるものなので、
     どれか1つのページの中だけに書いても効かないため -->
<style>
/* ============================================================
   スクロールバーの場所を、いつも空けておく

   ゲーム本編（/）は画面にぴったり収まるので、縦のスクロールバーが出ない
   サウンドトラック（/soundtrack）は縦に長いので、スクロールバーが出る

   そのままページを行き来すると、
   「スクロールバーが出る → そのぶん中身の幅がせまくなる」
   「スクロールバーが消える → そのぶん広くなる」
   がくりかえされて、画面の中身が15pxほど左右にカクッと動いてしまう
   （どちらのページも max-width ＋ margin: 0 auto で真ん中ぞろえのため、
     幅が変わると、まんなかの位置もずれる）

   scrollbar-gutter: stable は、
   「スクロールバーが出ていないときも、その場所だけは空けておく」という指定
   こうすると、どちらのページでも中身の幅が変わらないので、行き来しても横にずれない

   ※ 灰色のスクロールバーがいつも見えるようになるわけではない
     空けてあるのは場所だけで、そこには下地（html の紺色）が見える
   ============================================================ */
html {
  scrollbar-gutter: stable;
}

/* ============================================================
   ページの切りかえ（はじめの画面 ⇄ サウンドトラック）のフェード

   ゲーム本編の中の画面（A画面・B画面・ゲーム画面）は
   同じページの中での切りかえなので、pages/index.vue の
   <Transition name="screen-fade"> がフェードさせている

   こちらは「ページそのもの」が入れかわるときの担当
   nuxt.config.ts の pageTransition で name: 'page-fade' を指定してあるので、
   クラス名は page-fade-〜 になる

   mode: 'out-in'（nuxt.config.ts のほうで指定）＝
   前のページが消えきってから、次のページを出す
   2ページが同時に出ないので、画面がガタッと動かない

   うれしいのは、消えていくページの中身がそのまま残ること
   サウンドトラックから戻るときは、音だけ先に止めて、
   「♪ 全曲再生中」や再生バーは見えたままフェードアウトしていく
   （表示を消す後片づけは、ページが消えたあとの onUnmounted にまかせてある）

   動きは、ゲーム本編の画面の切りかえとそろえてある
   ・opacity（すけ具合）
   ・translateY（ほんの2〜4pxの上下）
   ・0.18秒（180ミリ秒）
   ============================================================ */
.page-fade-enter-active,
.page-fade-leave-active {
  transition:
    opacity 0.18s ease,
    transform 0.18s ease;
}

/* 出てくるとき：4pxだけ下から、すっと上がりながら現れる */
.page-fade-enter-from {
  opacity: 0;
  transform: translateY(4px);
}

/* 消えるとき：2pxだけ上へ抜けながら消える */
.page-fade-leave-to {
  opacity: 0;
  transform: translateY(-2px);
}

/* 消えかけのページは、もう押せないようにする
   （移動中に、前のページのボタンを続けて押せてしまわないように） */
.page-fade-leave-active {
  pointer-events: none;
}

/* 動きを減らす設定にしている人には、フェードをほとんど無くす
   （切りかわることは同じで、動きだけを取りのぞく） */
@media (prefers-reduced-motion: reduce) {
  .page-fade-enter-active,
  .page-fade-leave-active {
    transition-duration: 0.01ms;
  }
}
</style>
