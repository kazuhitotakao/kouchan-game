<!-- ここのCSSには scoped を付けない（＝ページ全体に効く共通のCSS）

     ページの入れかわり（/ ⇄ /soundtrack）に使うクラスは、
     Nuxtがページの外側から付けるものなので、
     どれか1つのページの中だけに書いても効かないため -->
<style>
/* ページ全体で共通に使う @keyframes（danger-pulse／found-in）

   scoped が付かない、この <style> から読みこむことで、
   @keyframes の名前が付けかえられないようにしている
   （くわしい理由は、読みこむ先のファイルの先頭に書いてある）

   ※ @import は、CSSの決まりで <style> のいちばん先頭に置く必要がある */
@import '~/assets/css/game/keyframes.css';

/* ちょっとしたできごと／ナイス対応の枠（.event-flash 〜）

   ResultCard.vue と pages/index.vue の両方で使うので、
   どちらか片方の scoped CSS に入れると、もう片方に届かない
   （くわしい理由は、読みこむ先のファイルの先頭に書いてある） */
@import '~/assets/css/game/event-flash.css';

/* 「どうする？」のコマンド欄（.command-box 〜）

   CommandBox.vue と pages/index.vue（秘密の小道）の両方で使うので、
   どちらか片方の scoped CSS に入れると、もう片方に届かない
   （くわしい理由は、読みこむ先のファイルの先頭に書いてある） */
@import '~/assets/css/game/command-shared.css';

/* ============================================================
   スクロールバーの場所を、いつも空けておく

   ゲーム本編（/）は画面にぴったり収まるので、縦のスクロールバーが出ない
   サウンドトラック（/soundtrack）は縦に長いので、スクロールバーが出る

   そのままページを行き来すると、
   「スクロールバーが出る → そのぶん中身の幅がせまくなる」
   「スクロールバーが消える → そのぶん広くなる」
   がくりかえされて、画面の中身が15pxほど左右にカクッと動いてしまう
   （どちらのページも max-width ＋ margin: 0 auto で真ん中ぞろえのため、
     幅が変わると、まんなかの位置もずれる）

   scrollbar-gutter: stable は、
   「スクロールバーが出ていないときも、その場所だけは空けておく」という指定
   こうすると、どちらのページでも中身の幅が変わらないので、行き来しても横にずれない

   ※ 灰色のスクロールバーがいつも見えるようになるわけではない
     空けてあるのは場所だけで、そこには下地（html の紺色）が見える
   ============================================================ */
html {
  scrollbar-gutter: stable;
}

/* ============================================================
   画面のはしで、ページ全体が「ばね」のように動かないようにする

   スマホでは、次のようなときに、ページ全体が上下にぐにゃっと動いてしまう
   ・スクロールしない場所（ゲーム画面の上部ステータスなど）を、指で上下にフリックしたとき
   ・ページや中の一覧を、いちばん上／下までスクロールして、さらにフリックしたとき
   ・（Android の Chrome）いちばん上で下へ引っぱったとき（引っぱって再読み込み）

   overscroll-behavior: none は、この「はしまで来たあとの動き」だけを止める指定
   ・スクロールそのものは止めない
     あそびかた・リザルトのように画面より長いページは、今までどおりスクロールして読める
   ・ゲーム本編（/）もサウンドトラック（/soundtrack）も、すべての画面に効く

   ※ ブラウザで開いたときは、引っぱって再読み込みする操作もできなくなる
     （ホーム画面に追加したアプリの画面には、もともとこの操作が無い）
   ※ iOS の Safari は 16 から対応。それより古いと、今までどおり「ばね」の動きが出る
   ============================================================ */
html,
body {
  overscroll-behavior: none;
}

/* ============================================================
   スマホでダブルタップしても、画面が拡大しないようにする

   iPhone では、ボタンのまわりの余白や文字のところを続けて2回タップすると、
   ダブルタップとして画面が拡大してしまう（user-scalable=no は iOS では効かない）
   拡大したあとは、もう一度ダブルタップするとボタンが反応してしまい、
   秘密の小道のフィールドは touch-action: none なので2本指でも縮められず、元に戻せなくなる

   touch-action: manipulation … ダブルタップの拡大だけを止める
   （2本指での拡大・スクロール・タップは、今までどおりできる）

   ・html だけでなく * （すべての要素）に付けている
     iPhone では、中でスクロールする箱（overflow-y: auto の .stage・.title-screen・結果カードの本文など）の
     ところで touch-action の効き目がリセットされ、外の箱に付けた指定が中まで届かないため
   ・* は詳細度が 0 なので、クラスで touch-action を決めている場所は、そちらがそのまま効く
     （秘密の小道のフィールドの none、サウンドトラックの上の操作エリアの pan-x pinch-zoom など）
   ・ゲーム本編（/）・ミニゲーム（/minigame 〜）・サウンドトラック（/soundtrack）の、すべての画面に効く
   ============================================================ */
* {
  touch-action: manipulation;
}

/* ============================================================
   ページの切りかえ（はじめの画面 ⇄ サウンドトラック）のフェード

   ゲーム本編の中の画面（A画面・B画面・ゲーム画面）は
   同じページの中での切りかえなので、pages/index.vue の
   <Transition name="screen-fade"> がフェードさせている

   こちらは「ページそのもの」が入れかわるときの担当
   nuxt.config.ts の pageTransition で name: 'page-fade' を指定してあるので、
   クラス名は page-fade-〜 になる

   mode: 'out-in'（nuxt.config.ts のほうで指定）＝
   前のページが消えきってから、次のページを出す
   2ページが同時に出ないので、画面がガタッと動かない

   うれしいのは、消えていくページの中身がそのまま残ること
   サウンドトラックから戻るときは、音だけ先に止めて、
   「♪ 全曲再生中」や再生バーは見えたままフェードアウトしていく
   （表示を消す後片づけは、ページが消えたあとの onUnmounted にまかせてある）

   動きは、ゲーム本編の画面の切りかえとそろえてある
   ・opacity（すけ具合）
   ・translateY（ほんの2〜4pxの上下）
   ・0.18秒（180ミリ秒）
   ============================================================ */
.page-fade-enter-active,
.page-fade-leave-active {
  transition:
    opacity 0.18s ease,
    transform 0.18s ease;
}

/* 出てくるとき：4pxだけ下から、すっと上がりながら現れる */
.page-fade-enter-from {
  opacity: 0;
  transform: translateY(4px);
}

/* 消えるとき：2pxだけ上へ抜けながら消える */
.page-fade-leave-to {
  opacity: 0;
  transform: translateY(-2px);
}

/* 消えかけのページは、もう押せないようにする
   （移動中に、前のページのボタンを続けて押せてしまわないように） */
.page-fade-leave-active {
  pointer-events: none;
}

/* 動きを減らす設定にしている人には、フェードをほとんど無くす
   （切りかわることは同じで、動きだけを取りのぞく） */
@media (prefers-reduced-motion: reduce) {
  .page-fade-enter-active,
  .page-fade-leave-active {
    transition-duration: 0.01ms;
  }
}
</style>
