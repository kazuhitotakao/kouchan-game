/* ============================================================
   疲れ・空腹で機嫌が下がる分の判定

   ゲーム本編（pages/index.vue）にあった dropMoodWhenTired() の
   「いくつ下がるかを決めているところ」だけを取り出してある

   ■ ここがやること
     体力と時間を見て、今回の行動で機嫌が下がる分を返す

   ■ ここがやらないこと
     ゲームの状態は、いっさい書きかえない（下がる分を返すだけ）
     機嫌を実際に減らすのは、受けとった pages/index.vue の dropMoodWhenTired() のまま

   ■ 下がる量・境目・判定の順番は、いっさい変えていない
     2つの理由がかさなったときに合計7下がるところも同じ

   ■ ぐずりだすライン（fussEnergyLine）は data/game.ts のものをそのまま使う
   ============================================================ */

import { fussEnergyLine } from '~/data/game';

/* 疲れたり、おなかがすいたりすると、だんだん機嫌もわるくなる

   機嫌が下がる理由は2つあり、両方かさなることもある
   ① 遊びつかれてきた … 体力が「ぐずりだすライン（71）」より下 → 機嫌 -4
   ② おなかがすいてきた … 11:00をすぎた                        → 機嫌 -3

   これが無いと、遊ぶ行動はどれも機嫌がふえるだけなので、
   機嫌はすぐ100に張りついて「見るだけの数字」になってしまう

   ②（時間）を入れているのは、控えめに遊ぶと体力がほとんど減らず、
   ①だけでは機嫌がまったく下がらなくなってしまうため
   お昼が近づけば、元気に遊んでいても だんだんぐずってくる、というルールにしている

   下がる力があることで、
   「もう1か所あそぶ？ 休む？ おやつを使う？ そろそろ帰る？」を
   最後まで考えられる数字になる

   ※ いやいやをなだめる行動ととつぜんのできごとでは呼ばれない
     （どちらも finishPlayAction() を通らないため）
     なだめている最中にさらに機嫌が下がると、立て直せなくなってしまう
*/
export function judgeMoodDrop(childEnergy: number, currentMinutes: number) {
  let moodDrop = 0;

  // ① 遊びつかれてきた
  if (childEnergy < fussEnergyLine) {
    moodDrop += 4;
  }

  // ② お昼が近づいて、おなかがすいてきた
  if (currentMinutes >= 11 * 60) {
    moodDrop += 3;
  }

  return moodDrop;
}
