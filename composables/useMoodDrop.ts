/* ============================================================
   疲れ・空腹で機嫌が下がる分の判定（下がる分を返すだけ。機嫌を減らすのは pages/index.vue の dropMoodWhenTired()）
   ============================================================ */

import { fussEnergyLine } from '~/data/game';

/* 疲れたり、おなかがすいたりすると、だんだん機嫌もわるくなる（両方かさなることもある）

   ① 遊びつかれてきた … 体力が「ぐずりだすライン（71）」より下 → 機嫌 -4
   ② おなかがすいてきた … 11:00をすぎた                        → 機嫌 -3

   これが無いと、遊ぶ行動はどれも機嫌がふえるだけで、機嫌はすぐ100に張りついて「見るだけの数字」になってしまう
   ②（時間）を入れているのは、控えめに遊ぶと体力がほとんど減らず、①だけでは機嫌がまったく下がらなくなるため
   下がる力があることで、「もう1か所あそぶ？ 休む？ おやつを使う？ 帰る？」を最後まで考えられる数字になる

   ※ いやいやをなだめる行動ととつぜんのできごとでは呼ばれない（なだめている最中に下がると、立て直せなくなるため） */
export function judgeMoodDrop(childEnergy: number, currentMinutes: number) {
  let moodDrop = 0;

  // ① 遊びつかれてきた
  if (childEnergy < fussEnergyLine) {
    moodDrop += 4;
  }

  // ② お昼が近づいて、おなかがすいてきた
  if (currentMinutes >= 11 * 60) {
    moodDrop += 3;
  }

  return moodDrop;
}
