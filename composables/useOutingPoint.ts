/* ============================================================
   おでかけポイントの加算量の計算

   ゲーム本編（pages/index.vue）にあった addOutingPoint() の
   「いくつ足すかを決めているところ」だけを取り出してある

   ■ ここがやること
     その場所を前にも探検しているかを見て、今回もらえるポイントを返す

   ■ ここがやらないこと
     ゲームの状態は、いっさい書きかえない（もらえる分を返すだけ）
     おでかけポイントを実際に足すのは、
     受けとった pages/index.vue の addOutingPoint() のまま

   ■ 半分にするときの切り捨てと、最低1点のところは、いっさい変えていない
   ============================================================ */

/* おでかけポイントを、今回いくつ足すか決める
   はじめての場所なら そのままのポイント
   2回目以降の場所なら 半分のポイント（小数点以下は切り捨て、最低1点）

   ※ 公園は6か所しかないので、2回目が1点しかもらえないと
     「全部まわったら、あとは帰るだけ」になってしまう
     半分もらえるようにすることで、体力が減ってきたときに
     「もう1か所あそぶ？ それとも帰る？」と迷えるようにしている
*/
export function judgeOutingPoint(point: number, isVisited: boolean) {
  if (isVisited) {
    const halfPoint = Math.floor(point / 2);

    return halfPoint < 1 ? 1 : halfPoint;
  }

  return point;
}
