/* ============================================================
   見つけたものの名前を、折り返してよい所で分ける

   日本語の名前は、せまい所では どこでも折り返してしまう（「ちいさな松ぼっ／くり」のように）
   そこで「ちいさな／松ぼっくり」の2つに分けて返し、画面は inline-block で包んで、そのあいだでだけ折り返す
   （入りきるときは、ふつうに1行で出る。「な」「の」が無い名前は、分けずにそのまま返す）
   ============================================================ */

/* 名前を、さいしょの「な」か「の」のあとで2つに分ける（分けられないときは、名前1つだけの配列） */
export function splitItemName(name: string): string[] {
  const match = /^(.+?[なの])(.+)$/.exec(name);

  return match ? [match[1], match[2]] : [name];
}
