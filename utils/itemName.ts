/* ============================================================
   見つけたものの名前を、折り返してよい所で分ける

   「ちいさな松ぼっくり」のような名前は、日本語なので言葉の区切りが無く、
   せまい所（リザルトのメダルの下・結果カードの「★ アイテム発見！」）では、
   入りきらなくなった文字の位置で、どこでも折り返してしまう
   （前は「ちいさな松ぼっ／くり」「大きなどんぐ／り」「水色のガラス／玉」のように、さいごの1〜2文字だけ次の行に落ちていた）

   そこで、名前を「ようすを表すことば」と「もの」の2つに分けて返す
   画面のほうは、分けたものを1つずつ <span>（inline-block）で包んで ならべるので、
   折り返すのは そのあいだ だけになる
     ちいさな／松ぼっくり　大きな／どんぐり　水色の／ガラス玉　ふしぎな／形の枝　きれいな／石
   ・入りきるときは、ふつうに1行で出る（分けたことは見た目には分からない）
   ・「な」「の」が無い名前（「きいろい花」など）は、分けずにそのまま1つで返す
   ・名前のデータ（data/places.ts の placeItems）は変えない。分けるのは画面に出すときだけ
   ============================================================ */

/* 名前を、さいしょの「な」か「の」のあとで2つに分ける（分けられないときは、名前1つだけの配列） */
export function splitItemName(name: string): string[] {
  const match = /^(.+?[なの])(.+)$/.exec(name);

  return match ? [match[1], match[2]] : [name];
}
