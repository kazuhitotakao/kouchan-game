/* ============================================================
   ステータスの増減を画面に出すときの、見た目用の小さな処理

   ゲーム本編（pages/index.vue）の結果カード・スコア内訳と、
   上部ステータス（components/game/StatusBar.vue）の両方で使うので、ここ1か所にまとめてある
   （2か所に同じ関数を書くと、片方だけ直して色や形がずれてしまうため）

   ここにあるのは「数字 → 文字」「数字 → CSSのクラス名」の変換だけで、
   ステータスの値を書きかえたり、ゲームのルールを決めたりはしない
   ============================================================ */

/* 変化量を「+5」「-10」「0」の形の文字にする */
export function formatChange(value: number) {
  return value > 0 ? `+${value}` : String(value);
}

/* 変化が「良い」「悪い」「変化なし」のどれかを判定して、CSSのクラス名を返す

   ステータスは4つとも「100に近いほど良い・0に近いほど危ない」でそろえてあるので、
   判定はとてもシンプルになる
     ・プラス（ふえた） → 良い変化
     ・マイナス（減った） → 悪い変化
   ※ 時間だけは、どの行動でも必ずふえるので色はつけない
*/
export function changeClass(statusName: string, value: number) {
  // 時間は良い・悪いで見ないので、いつも「変化なし」の色にする
  if (statusName === 'minutes') {
    return 'change--neutral';
  }

  if (value === 0) {
    return 'change--neutral';
  }

  // 体力・機嫌・ポイント・親の余裕は、どれも ふえると良い変化
  return value > 0 ? 'change--good' : 'change--bad';
}
